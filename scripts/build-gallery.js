/* Builds media/gallery.js: the curated open-model gallery with each model's
 * silhouette pre-computed from its Hub headers (header-only, a few MB total).
 *   node scripts/build-gallery.js [cacheDir]
 * Re-run after editing MODELS. A cacheDir of saved loadFromHub() JSON skips the network. */
const fs = require('fs');
const path = require('path');
const { loadFromHub } = require('../lib/hub');
require('../media/anatomy');

const MODELS = [
  ['Write text', [
    ['openai-community/gpt2', 'GPT-2', 'OpenAI', 'OpenAI’s 2019 text model. Small by today’s standards, and where most tutorials start.'],
    ['HuggingFaceTB/SmolLM2-135M-Instruct', 'SmolLM2 135M', 'Hugging Face', 'A tiny chat model, trained to stay useful at phone size.'],
    ['unsloth/gemma-3-270m-it', 'Gemma 3 270M', 'Google · Unsloth mirror', 'Google’s smallest Gemma. Most of its weight is its 262,144-token vocabulary.'],
    ['Qwen/Qwen3-0.6B', 'Qwen3 0.6B', 'Alibaba Qwen', 'The smallest Qwen3. It can answer quickly or think step by step first.'],
    ['unsloth/Llama-3.2-1B-Instruct', 'Llama 3.2 1B', 'Meta · Unsloth mirror', 'Meta’s 1-billion-parameter Llama, built for chat on your own device.'],
    ['deepseek-ai/DeepSeek-R1-Distill-Qwen-1.5B', 'R1 Distill 1.5B', 'DeepSeek', 'A small Qwen model that learned to reason by studying DeepSeek-R1’s answers.'],
    ['microsoft/Phi-4-mini-instruct', 'Phi-4 mini', 'Microsoft', 'A 3.8B model trained largely on synthetic, textbook-style data.'],
    ['mistralai/Mistral-7B-Instruct-v0.3', 'Mistral 7B', 'Mistral AI', 'The 7B model that showed small open models could keep up with big ones.'],
  ]],
  ['Mixture of experts', [
    ['Qwen/Qwen3-30B-A3B', 'Qwen3 30B-A3B', 'Alibaba Qwen', '30 billion parameters, but each token only uses about 3 billion of them.'],
    ['openai/gpt-oss-20b', 'gpt-oss 20B', 'OpenAI', 'OpenAI’s open reasoning model. Its experts are stored in 4-bit so it fits in 16 GB.'],
    ['deepseek-ai/DeepSeek-V3', 'DeepSeek-V3', 'DeepSeek', '671B parameters and 256 experts per block. DeepSeek-R1 was trained from it.'],
    ['moonshotai/Kimi-K2-Instruct', 'Kimi K2', 'Moonshot AI', 'A trillion parameters, with 384 experts in every block.'],
  ]],
  ['See and read', [
    ['HuggingFaceTB/SmolVLM-256M-Instruct', 'SmolVLM 256M', 'Hugging Face', 'A tiny model that looks at an image and answers questions about it.'],
    ['Qwen/Qwen2.5-VL-3B-Instruct', 'Qwen2.5-VL 3B', 'Alibaba Qwen', 'Reads photos, screenshots and documents, then answers in text.'],
    ['google/siglip-base-patch16-224', 'SigLIP', 'Google', 'Scores how well a caption fits a picture. Many vision-language models use it as their eyes.'],
  ]],
  ['Listen', [
    ['openai/whisper-small', 'Whisper small', 'OpenAI', 'Speech in, transcript out, in 99 languages.'],
  ]],
  ['Understand text', [
    ['google-bert/bert-base-uncased', 'BERT base', 'Google', 'The 2018 model that reads in both directions. It understands text rather than writing it.'],
  ]],
];

(async () => {
  const cache = process.argv[2];
  const groups = [];
  for (const [title, items] of MODELS) {
    const out = [];
    for (const [id, name, maker, blurb] of items) {
      const f = cache && path.join(cache, id.replace('/', '__') + '.json');
      const model = f && fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : await loadFromHub(id);
      out.push({ id, name, maker, blurb, ...WLA.silhouette(WLA.analyze(model)) });
      console.log('✓', id);
    }
    groups.push({ title, items: out });
  }
  const js = '/* generated by scripts/build-gallery.js — do not edit */\nwindow.WL_GALLERY = ' + JSON.stringify(groups) + ';\n';
  fs.writeFileSync(path.join(__dirname, '..', 'media', 'gallery.js'), js);
  console.log(`media/gallery.js · ${(js.length / 1024).toFixed(1)} KB`);
})().catch((e) => { console.error(e); process.exit(1); });
